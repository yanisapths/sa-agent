import type { z } from "zod";
import {
  CONNECTION_KINDS,
  CONNECTION_SOURCES,
  confluenceConnectionSchema,
  figmaConnectionSchema,
  jiraConnectionSchema,
  postgresConnectionSchema,
} from "./connection";

const VARIANTS = {
  PostgresConnection: postgresConnectionSchema,
  ConfluenceConnection: confluenceConnectionSchema,
  JiraConnection: jiraConnectionSchema,
  FigmaConnection: figmaConnectionSchema,
} as const;

function fieldType(field: z.ZodType): string {
  const def = field._zod.def as { type: string; values?: unknown[] };
  if (def.type === "literal" && def.values) return def.values.map((v) => JSON.stringify(v)).join(" | ");
  return "string";
}

function variant(name: string, schema: z.ZodObject): string {
  const fields = Object.entries(schema.shape).map(([key, field]) => {
    const optional = (field as z.ZodType)._zod.optin === "optional" ? "?" : "";
    return `  ${key}${optional}: ${fieldType(field as z.ZodType)};`;
  });
  return `export type ${name} = {\n${fields.join("\n")}\n};`;
}

/** `frontend/lib/connection.ts`: what the browser may put in `X-SA-Connections`. */
export function frontendConnectionModule(): string {
  const types = Object.entries(VARIANTS).map(([name, schema]) => variant(name, schema));
  return `// Generated by \`bun run surfaces\` from backend/contract/connection.ts. Do not edit.

export const CONNECTIONS_HEADER = "X-SA-Connections";
export const MAX_CONNECTIONS_HEADER_BYTES = 8 * 1024;

export const CONNECTION_KINDS = ${JSON.stringify(CONNECTION_KINDS)} as const;
export type ConnectionKind = (typeof CONNECTION_KINDS)[number];

export const CONNECTION_SOURCES = ${JSON.stringify(CONNECTION_SOURCES)} as const;
export type ConnectionSource = (typeof CONNECTION_SOURCES)[number];
export type ConnectionSources = Partial<Record<ConnectionKind, ConnectionSource>>;

${types.join("\n\n")}

export type Connection =
${Object.keys(VARIANTS).map((name) => `  | ${name}`).join("\n")};

export type ConnectionOf<K extends ConnectionKind> = Extract<Connection, { kind: K }>;
`;
}
